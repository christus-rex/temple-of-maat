  function installGateway() {
    const staticNav = document.querySelector('#temple-static-entry .temple-static-entry__actions');
    if (staticNav && !staticNav.querySelector('[data-poems-chamber="static"]')) {
      const link = document.createElement('a');
      link.className = 'temple-static-entry__action temple-static-entry__action--secondary';
      link.href = '#poems-chamber';
      link.dataset.poemsChamber = 'static';
      link.textContent = 'Enter the Poems Chamber';
      staticNav.appendChild(link);
    }

    if (!document.querySelector('[data-poems-chamber="floating"]')) {
      const gateway = document.createElement('a');
      gateway.className = 'temple-poems-gateway';
      gateway.href = '#poems-chamber';
      gateway.dataset.poemsChamber = 'floating';
      gateway.setAttribute('aria-label', 'Open the Poems Chamber');
      gateway.innerHTML = '<span class="temple-poems-gateway__sigil" aria-hidden="true">❧</span><span>POEMS<span class="temple-poems-gateway__long"> · CHAMBER</span></span>';
      document.body.appendChild(gateway);
    }
  }

